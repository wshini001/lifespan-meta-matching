"""Assign ABCD outer folds using the selected cohort's existing row order.

Uses shuffled participant-level KFold splits. The selected-cohort input
can be generated by infer_source_dnn.py.
"""

import argparse
import json
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.model_selection import KFold


def assign_folds(n_rows, outer_k, seed):
    folds = np.full(n_rows, -1, dtype=np.int64)
    cv = KFold(n_splits=outer_k, shuffle=True, random_state=seed)
    for fold, (_, test) in enumerate(cv.split(np.empty((n_rows, 0)))):
        folds[test] = fold
    if np.any(folds < 0):
        raise RuntimeError("Some rows were not assigned to an outer fold.")
    return folds


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--selected-cohort-csv", required=True)
    p.add_argument(
        "--config", default=str(Path(__file__).parent / "config/final43.json")
    )
    p.add_argument("--out-dir", required=True)
    args = p.parse_args()
    config = json.loads(Path(args.config).read_text())
    frame = pd.read_csv(args.selected_cohort_csv)
    id_col = config["id_col"]
    subjectkey = config["subjectkey_col"]
    target = config["target_col"]
    required = ["_orig_row_idx", subjectkey, id_col, target]
    if any((c not in frame for c in required)):
        raise ValueError(f"Selected cohort must contain {required}.")
    if len(frame) != config["expected_n_subjects"]:
        raise ValueError("Selected cohort size differs from the reported sample.")
    if (
        frame[required].isna().any().any()
        or frame[id_col].astype(str).duplicated().any()
    ):
        raise ValueError("Missing selection fields or duplicate participant IDs.")
    frame["_orig_row_idx"] = pd.to_numeric(
        frame["_orig_row_idx"], errors="raise"
    ).astype(np.int64)
    if frame["_orig_row_idx"].duplicated().any() or (frame["_orig_row_idx"] < 0).any():
        raise ValueError("Invalid original row indices.")
    frame[target] = pd.to_numeric(frame[target], errors="raise").astype(np.float32)
    if not np.isfinite(frame[target]).all():
        raise ValueError("Nonfinite target values.")
    fields = [
        "_orig_row_idx",
        subjectkey,
        id_col,
        "interview_date",
        "age",
        "Age_years",
        "sex",
        "Sex",
        "site",
        target,
    ]
    frame = frame[[c for c in fields if c in frame]].copy()
    folds = assign_folds(len(frame), config["outer_k"], config["seed"])
    frame["fold"] = folds
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    frame.to_csv(out / "outer_folds_manifest.csv", index=False)
    np.savez(
        out / "outer_folds.npz",
        fold_id=folds,
        outer_k=np.int64(config["outer_k"]),
        seed=np.int64(config["seed"]),
        n_subjects=np.int64(len(frame)),
    )
    metadata = {
        "selected_cohort_csv": args.selected_cohort_csv,
        "outer_k": config["outer_k"],
        "seed": config["seed"],
        "n_subjects": len(frame),
        "splitter": "shuffled participant KFold",
        "cohort_order": "selected-cohort file order, unchanged",
    }
    (out / "fold_lock_metadata.json").write_text(json.dumps(metadata, indent=2))
    print("Fold counts:", frame.groupby("fold").size().to_dict())
    print("ABCD folds generated and participant identities checked.")


if __name__ == "__main__":
    main()
